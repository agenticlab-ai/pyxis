// templateBlocks returns the fenced markdown blocks of the shipped template.
func templateBlocks(t *testing.T) []string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("..", "..", ".pyxis", "templates", "pr-description-template.md"))
	if err != nil {
		t.Fatal(err)
	}
	var blocks []string
	for _, part := range strings.Split(string(raw), "````markdown\n")[1:] {
		block, _, ok := strings.Cut(part, "\n````")
		if !ok {
			t.Fatal("unterminated example block in the template")
		}
		blocks = append(blocks, block)
	}
	if len(blocks) != 2 {
		t.Fatalf("the template has %d example blocks; want the skeleton and the worked example", len(blocks))
	}
	return blocks
}

func TestTemplateFileMatchesTheChecker(t *testing.T) {
	blocks := templateBlocks(t)
	_, problems := Parse(blocks[0])
	for _, p := range problems {
		if p.Field == "" || strings.Contains(p.Message, "missing") {
			t.Errorf("the template's skeleton has a structural problem: %s", p)
		}
	}
	if problems := Check(blocks[1], size(101, 38)); len(problems) != 0 {
		t.Fatalf("the template's worked example fails the check: %v", messages(problems))
	}
}

func TestPublishFollowsTheOptimisticProtocol(t *testing.T) {
	rendered := Description{What: "new"}.Render()
	stale := "top\n" + Description{What: "old"}.Render() + "\nbottom\n"
	t.Run("writes once and verifies", func(t *testing.T) {
		body, writes := stale, 0
		err := Publish(context.Background(), rendered, func(context.Context) (string, error) { return body, nil },
			func(_ context.Context, b string) error { writes++; body = b; return nil })
		if err != nil || writes != 1 || body != Replace(stale, rendered) {
			t.Fatalf("err=%v writes=%d body=%q", err, writes, body)
		}
	})
	t.Run("an unchanged description is not rewritten", func(t *testing.T) {
		body := Replace(stale, rendered)
		err := Publish(context.Background(), rendered, func(context.Context) (string, error) { return body, nil },
			func(context.Context, string) error { t.Fatal("rewrote an unchanged description"); return nil })
		if err != nil {
			t.Fatal(err)
		}
	})
	t.Run("a concurrent edit is never overwritten", func(t *testing.T) {
		bodies := []string{stale, stale + "edit", stale + "edit", stale + "edit"}
		reads, written := 0, ""
		read := func(context.Context) (string, error) {
			b := bodies[min(reads, len(bodies)-1)]
			reads++
			if written != "" {
				return written, nil
			}
			return b, nil
		}
		if err := Publish(context.Background(), rendered, read, func(_ context.Context, b string) error { written = b; return nil }); err != nil {
			t.Fatal(err)
		}
		if !strings.HasSuffix(written, "edit") {
			t.Fatalf("the concurrent edit was lost: %q", written)
		}
	})
	t.Run("failures", func(t *testing.T) {
		boom := errors.New("boom")
		for name, c := range map[string]struct {
			failRead int
			writeErr error
		}{"first read": {failRead: 1}, "re-read": {failRead: 2}, "read back": {failRead: 3}, "write": {writeErr: boom}} {
			reads := 0
			read := func(context.Context) (string, error) {
				reads++
				if reads == c.failRead {
					return "", boom
				}
				return stale, nil
			}
			if err := Publish(context.Background(), rendered, read, func(context.Context, string) error { return c.writeErr }); !errors.Is(err, boom) {
				t.Errorf("%s: %v", name, err)
			}
		}
		read := func(context.Context) (string, error) { return stale, nil }
		if err := Publish(context.Background(), rendered, read, func(context.Context, string) error { return nil }); err == nil || !strings.Contains(err.Error(), "did not stabilize") {
			t.Fatalf("a write that never sticks: %v", err)
		}
	})
}
