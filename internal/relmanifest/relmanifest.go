// Package relmanifest owns the installer design's two closed release-metadata
// contracts and the walk that derives one from the other (installer-v1
// §3.1–§3.2; solution shape docs/solution-shapes/installer-v1.md):
//
//   - class-policy/v1 — the authored ownership-class input (AP-24): an
//     ORDERED list of {glob, class} rules, first match wins, committed at
//     .pyxis/class-policy.yaml in the source repo.
//   - release-manifest/v2 — the derived trust-root object (AP-27): per-file
//     sha256 + ownership class for every installed file, per-binary
//     per-platform hashes, the system version and source commit, and the
//     payload archive hash. The dependency-bundle hash is optional in v2;
//     legacy v1 manifests still require it. Generated by the release build
//     via Walk, never authored.
//
// Both schemas parse CLOSED (DINV-2): an unknown key, an unknown ownership
// class, a hash inconsistent with its class, or trailing content is a named
// defect. Walk derives a manifest from a packed payload tree: every file is
// classed by the policy or the walk fails naming exactly the unmatched files
// (DINV-6, A-11).
//
// The payload tree Walk sees is the tree AS PACKED. The packer stages tracked
// content only, so gitignored caches — .pyxis/bin/, .pyxis/feedback-queue/,
// .pyxis/contract-gate-reports/, vendor node_modules/, .pyxis/scratch/ scratch —
// never enter the payload and carry no policy rows; Walk therefore never
// excludes anything itself, it classes exactly what it is handed.
//
// The policy's YAML grammar is the same hand-rolled closed subset
// internal/docgate/config uses (stdlib only, per the repo Go rules): one
// top-level scalar, one top-level list of single-line flow maps, comments and
// blank lines; anything richer is a defect.
package relmanifest

import "fmt"

// Current schema identifiers and the supported legacy manifest schema.
const (
	PolicySchemaVersion         = "class-policy/v1"
	ManifestSchemaVersion       = "release-manifest/v2"
	legacyManifestSchemaVersion = "release-manifest/v1"
)

// Class is the ownership class an installed file carries (installer-v1 §3.2):
// converge repairs engine-verbatim files byte-exact, validates repo-owned
// files against their closed schemas without ever rewriting them, and
// regenerates generated files.
type Class string

// The three ownership classes — a closed enum; anything else is a defect.
const (
	EngineVerbatim Class = "engine-verbatim"
	RepoOwned      Class = "repo-owned"
	Generated      Class = "generated"
)

// parseClass admits exactly the three ownership classes.
func parseClass(s string) (Class, error) {
	switch c := Class(s); c {
	case EngineVerbatim, RepoOwned, Generated:
		return c, nil
	}
	return "", fmt.Errorf("unknown ownership class %q (want %s, %s, or %s)", s, EngineVerbatim, RepoOwned, Generated)
}
