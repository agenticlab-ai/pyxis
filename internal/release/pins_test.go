// pinsDownloadSteps is the published-release transcript: one download per
// pinned artifact, in derivation order, then SHA256SUMS.
func pinsDownloadSteps(t *testing.T, out string, sums []byte) []ghStep {
	t.Helper()
	names := []string{"release-manifest-" + fixtureVersion + ".json"}
	for _, plat := range release.Platforms {
		names = append(names, "pyxis-"+fixtureVersion+"-"+plat)
	}
	var steps []ghStep
	for _, name := range names {
		body, err := os.ReadFile(filepath.Join(out, name))
		if err != nil {
			t.Fatal(err)
		}
		steps = append(steps, pinsDownloadStep(name, body))
	}
	return append(steps, pinsDownloadStep(release.SumsName, sums))
}

func pinsDownloadStep(name string, deliver []byte) ghStep {
	return ghStep{
		check: func(t *testing.T, args []string) {
			t.Helper()
			if !slices.Equal(args[:6], []string{"release", "download", fixtureVersion, "--repo", pinsSourceRepo, "--pattern"}) || args[6] != name {
				t.Fatalf("gh args = %v, want a download of %s", args, name)
			}
		},
		deliver: deliver,
	}
}

// The published-release leg: with no --out, the anchor is derived from the
// bytes the release actually serves — hashed here, then cross-checked
// against the release's own SHA256SUMS.
func TestPinsFromPublishedRelease(t *testing.T) {
	repo := fixtureRepo(t)
	stalePinsInstallSH(t, repo)
	out, _ := packFixture(t, repo)
	sums, err := os.ReadFile(filepath.Join(out, release.SumsName))
	if err != nil {
		t.Fatal(err)
	}

	gh := &fakeGH{t: t, steps: pinsDownloadSteps(t, out, sums)}
	res, err := release.Pins(context.Background(), release.PinsOptions{
		Version: fixtureVersion, RepoRoot: repo, SourceRepo: pinsSourceRepo, Runner: gh,
	})
	if err != nil {
		t.Fatalf("pins: %v", err)
	}
	gh.done()
	if res.Action != "written" || !strings.Contains(res.Source, pinsSourceRepo) {
		t.Errorf("action/source = %q/%q", res.Action, res.Source)
	}
	// Identical to what the local leg derives from the same set.
	if got, want := res.Pins.ManifestSHA, sumOf(t, out, "release-manifest-"+fixtureVersion+".json"); got != want {
		t.Errorf("manifest pin = %s, want %s", got, want)
	}
	for _, plat := range release.Platforms {
		if got, want := res.Pins.Binaries[plat], sumOf(t, out, "pyxis-"+fixtureVersion+"-"+plat); got != want {
			t.Errorf("%s pin = %s, want %s", plat, got, want)
		}
	}
}

// A release whose SHA256SUMS disagrees with the bytes it serves is a named
// refusal — the anchor is never taken from a self-contradicting set.
func TestPinsFromPublishedReleaseRefusesInconsistentSums(t *testing.T) {
	repo := fixtureRepo(t)
	stalePinsInstallSH(t, repo)
	out, _ := packFixture(t, repo)
	before := readInstallSH(t, repo)

	sums, err := os.ReadFile(filepath.Join(out, release.SumsName))
	if err != nil {
		t.Fatal(err)
	}
	name := "pyxis-" + fixtureVersion + "-darwin-arm64"
	tampered := strings.Replace(string(sums),
		sumOf(t, out, name)+"  "+name,
		strings.Repeat("f", 64)+"  "+name, 1)

	gh := &fakeGH{t: t, steps: pinsDownloadSteps(t, out, []byte(tampered))}
	_, err = release.Pins(context.Background(), release.PinsOptions{
		Version: fixtureVersion, RepoRoot: repo, SourceRepo: pinsSourceRepo, Runner: gh,
	})
	if err == nil || !strings.Contains(err.Error(), "not self-consistent") || !strings.Contains(err.Error(), name) {
		t.Fatalf("err = %v, want the inconsistent-set refusal naming %s", err, name)
	}
	gh.done()
	if after := readInstallSH(t, repo); after != before {
		t.Error("a refused run still rewrote install.sh")
	}
}

// An unfetchable release refuses with the WHOLE gap named — every pinned
// artifact, not just the first miss — so one run tells the operator what is
// actually wrong (a typo'd tag, an unpublished release).
func TestPinsFromPublishedReleaseRefusesMissingArtifacts(t *testing.T) {
	repo := fixtureRepo(t)
	stalePinsInstallSH(t, repo)
	notFound := ghStep{
		check:  func(t *testing.T, args []string) { t.Helper() },
		stderr: "release not found",
		exit:   1,
	}
	steps := make([]ghStep, 0, 1+len(release.Platforms))
	for i := 0; i <= len(release.Platforms); i++ {
		steps = append(steps, notFound)
	}
	gh := &fakeGH{t: t, steps: steps}
	_, err := release.Pins(context.Background(), release.PinsOptions{
		Version: fixtureVersion, RepoRoot: repo, SourceRepo: pinsSourceRepo, Runner: gh,
	})
	if err == nil {
		t.Fatal("err = nil, want a refusal")
	}
	gh.done()
	want := []string{"release-manifest-" + fixtureVersion + ".json"}
	for _, plat := range release.Platforms {
		want = append(want, "pyxis-"+fixtureVersion+"-"+plat)
	}
	for _, name := range want {
		if !strings.Contains(err.Error(), name) {
			t.Errorf("refusal does not name %s:\n%v", name, err)
		}
	}
}

