#!/bin/sh
# pyxis installer — one-liner machine install of the `pyxis` CLI.
#
# No account, credential, or GitHub CLI is needed:
#
#   curl -fsSL https://raw.githubusercontent.com/agenticlab-ai/pyxis/main/install.sh | sh
#
# The version + per-platform sha256 pins this script carries ARE the trust
# anchor (an anchor independent of the release itself; installer-v1 §3.4). It
# downloads the pinned `pyxis` binary from the public GitHub release, verifies its
# bytes against that pin BEFORE anything runs, installs the CLI, and delegates
# zsh setup to it. Run `pyxis init` yourself inside whichever repo you want to set
# up.
#
# Env overrides (all optional):
#   PYXIS_VERSION          release tag to install (default: the pinned version below)
#   PYXIS_INSTALL_DIR      install target directory (default: ~/.local/bin)
#   PYXIS_ARTIFACT_SOURCE  fetch base override — file:// (air-gap / local) or
#                          https:// (mirror); flat <base>/<name>.
#   PYXIS_RELEASE_TOKEN_ENV  name of the variable holding a token for a PRIVATE
#                          GitHub fork; that one case still needs an authenticated
#                          `gh`, because a private asset's download URL 404s.
#   PYXIS_SHA256           override the expected sha for THIS platform (advanced;
#                          required when PYXIS_VERSION is not the pinned one)
#
# POSIX sh; bash-3.2-clean. A checksum refusal installs nothing. A later setup
# failure exits non-zero and names the recovery command.
set -eu

REPO="agenticlab-ai/pyxis"
RELEASE_PROVIDER="${PYXIS_RELEASE_PROVIDER:-github}"
RELEASE_BASE_URL="${PYXIS_RELEASE_BASE_URL:-https://github.com}"
REPO="${PYXIS_RELEASE_REPOSITORY:-$REPO}"
RELEASE_TOKEN_ENV="${PYXIS_RELEASE_TOKEN_ENV:-}"

# ---- release pins (THE trust anchor; regenerated by the release process) ----
# BEGIN PINS v0.2.0
PINNED_VERSION="v0.2.0"
MANIFEST_SHA256="2ec091772c103ed397d30dcf7a10a471cd3ffe0cba08f1a6008bea044081dcb6"
sha_darwin_amd64="f96817199f91c992a2b6a84837377b6002d6475cabdaa507998648501ec8391c"
sha_darwin_arm64="f9573fa66fa20855f3eb386a7365888c0d1f126f75fd982b2c154183e9b879ad"
sha_linux_amd64="476addfa9a37c9cdb24347eb11cee5e5befa94f5be489056eea50dd8887ea020"
sha_linux_arm64="2a655e56062f71e53e05f26b61ca392c9d14d4439421230ca600647f596b8eec"
# END PINS

VERSION="${PYXIS_VERSION:-$PINNED_VERSION}"
INSTALL_DIR="${PYXIS_INSTALL_DIR:-$HOME/.local/bin}"

# ---- detect this machine's platform in the release's naming ----
OS="$(uname | tr 'A-Z' 'a-z')"
ARCH="$(uname -m)"
case "$ARCH" in
  x86_64|amd64) ARCH="amd64" ;;
  aarch64|arm64) ARCH="arm64" ;;
  *) echo "pyxis-install: unsupported architecture '$ARCH' (want x86_64/arm64)" >&2; exit 2 ;;
esac
case "$OS" in
  darwin|linux) ;;
  *) echo "pyxis-install: unsupported OS '$OS' (want darwin/linux)" >&2; exit 2 ;;
esac
PLAT="$OS-$ARCH"
NAME="pyxis-$VERSION-$PLAT"

# ---- resolve the expected sha for this platform (fail closed) ----
if [ -n "${PYXIS_SHA256:-}" ]; then
  WANT="$PYXIS_SHA256"
elif [ "$VERSION" = "$PINNED_VERSION" ]; then
  eval "WANT=\${sha_$(printf '%s' "$PLAT" | tr '-' '_'):-}"
else
  WANT=""
fi
if [ -z "${WANT:-}" ]; then
  echo "pyxis-install: no sha256 pin for $PLAT at $VERSION." >&2
  echo "  This script pins $PINNED_VERSION; to install a different version, pass its" >&2
  echo "  checksum: PYXIS_VERSION=$VERSION PYXIS_SHA256=<hex> ... | sh" >&2
  exit 2
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/pyxis-install.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT INT TERM

# ---- fetch the pyxis binary ----
if [ -n "${PYXIS_ARTIFACT_SOURCE:-}" ]; then
  base="${PYXIS_ARTIFACT_SOURCE%/}"
  echo "pyxis-install: fetching $NAME from $base"
  case "$base" in
    file://*) cp "${base#file://}/$NAME" "$TMP/$NAME" 2>/dev/null \
        || { echo "pyxis-install: $NAME not found under ${base#file://}" >&2; exit 2; } ;;
    *) curl -fsSL "$base/$NAME" -o "$TMP/$NAME" \
        || { echo "pyxis-install: could not fetch $base/$NAME" >&2; exit 2; } ;;
  esac
elif [ "$RELEASE_PROVIDER" = "forgejo" ]; then
  RELEASE_TOKEN_ENV="${RELEASE_TOKEN_ENV:-PYXIS_FORGEJO_TOKEN}"
  case "$RELEASE_TOKEN_ENV" in ''|[0-9]*|*[!A-Za-z0-9_]*) echo "pyxis-install: invalid release token environment variable name" >&2; exit 2 ;; esac
  case "$RELEASE_BASE_URL" in https://*|http://127.0.0.1:*|http://localhost:*) ;; *) echo "pyxis-install: Forgejo requires HTTPS or a loopback HTTP URL" >&2; exit 2 ;; esac
  eval "RELEASE_TOKEN=\${$RELEASE_TOKEN_ENV:-}"
  case "$RELEASE_TOKEN" in *[!A-Za-z0-9_.-]*) echo "pyxis-install: malformed release token" >&2; exit 2 ;; esac
  URL="${RELEASE_BASE_URL%/}/$REPO/releases/download/$VERSION/$NAME"
  { [ -z "$RELEASE_TOKEN" ] || printf 'header = "Authorization: token %s"\n' "$RELEASE_TOKEN"; } |
    curl --config - -fsSL "$URL" -o "$TMP/$NAME" \
    || { echo "pyxis-install: Forgejo asset fetch failed from ${RELEASE_BASE_URL%/}" >&2; exit 2; }
elif [ "$RELEASE_PROVIDER" = "github" ] && [ -n "$RELEASE_TOKEN_ENV" ]; then
  case "$RELEASE_TOKEN_ENV" in [0-9]*|*[!A-Za-z0-9_]*) echo "pyxis-install: invalid release token environment variable name" >&2; exit 2 ;; esac
  eval "GH_TOKEN=\${$RELEASE_TOKEN_ENV:-}"
  [ -n "$GH_TOKEN" ] || { echo "pyxis-install: configured GitHub credential is missing" >&2; exit 2; }
  export GH_TOKEN
  command -v gh >/dev/null 2>&1 \
    || { echo "pyxis-install: a private GitHub release needs the GitHub CLI 'gh' (or set PYXIS_ARTIFACT_SOURCE)." >&2; exit 2; }
  echo "pyxis-install: downloading $NAME from $REPO release $VERSION via gh"
  gh release download "$VERSION" --repo "$REPO" --pattern "$NAME" --dir "$TMP" --clobber \
    || { echo "pyxis-install: gh release download failed; confirm $RELEASE_TOKEN_ENV can read $REPO and that release $VERSION is published." >&2; exit 2; }
elif [ "$RELEASE_PROVIDER" = "github" ]; then
  URL="https://github.com/$REPO/releases/download/$VERSION/$NAME"
  echo "pyxis-install: fetching $NAME from $URL"
  curl -fsSL "$URL" -o "$TMP/$NAME" \
    || { echo "pyxis-install: could not fetch $URL" >&2
         echo "  Confirm release $VERSION of $REPO is published, then retry." >&2; exit 2; }
else
  echo "pyxis-install: unsupported release provider '$RELEASE_PROVIDER'" >&2; exit 2
fi

# ---- verify BEFORE anything is installed (DINV-1: no unpinned byte survives) ----
# Select the digest tool ONCE. Written as `shasum … | cut … || sha256sum …`
# the fallback bound to the PIPELINE, whose status is cut's: on an image with
# no shasum (slim Ubuntu carries sha256sum but not the perl that ships it) the
# fallback never fired, sum returned nothing, and the empty digest was reported
# as a checksum mismatch against bytes that were intact.
if command -v sha256sum >/dev/null 2>&1; then sum() { sha256sum "$1" | cut -d' ' -f1; }
elif command -v shasum >/dev/null 2>&1; then sum() { shasum -a 256 "$1" | cut -d' ' -f1; }
elif command -v openssl >/dev/null 2>&1; then sum() { openssl dgst -sha256 "$1" | awk '{print $NF}'; }
else echo "pyxis-install: no sha256 tool found — need sha256sum, shasum, or openssl; refusing to install unverified bytes (DINV-1, fail closed)" >&2; exit 2; fi
GOT="$(sum "$TMP/$NAME")"
if [ -z "$GOT" ]; then
  echo "pyxis-install: could not compute a sha256 for $NAME — refusing to install unverified bytes." >&2
  exit 2
fi
if [ "$GOT" != "$WANT" ]; then
  echo "pyxis-install: checksum mismatch for $NAME — refusing to install." >&2
  echo "  want $WANT" >&2
  echo "  got  $GOT" >&2
  exit 1
fi

# ---- install the CLI ----
mkdir -p "$INSTALL_DIR"
chmod 0755 "$TMP/$NAME"
mv "$TMP/$NAME" "$INSTALL_DIR/pyxis"
echo "pyxis-install: installed pyxis $VERSION -> $INSTALL_DIR/pyxis"

# ---- hand off the release pin so `pyxis init` needs no flags ----
# This file delivers the manifest_sha256 anchor this script carries (not just
# convenience). init
# reads it when --system-version/--manifest-sha256 are unset; a flag or the
# PYXIS_* env vars override it. Only written for the pinned version, whose
# manifest sha this script carries.
if [ "$VERSION" = "$PINNED_VERSION" ] && [ -n "$MANIFEST_SHA256" ]; then
  CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/pyxis"
  mkdir -p "$CONFIG_DIR"
  # Record where this machine gets releases, so nothing later has to be told
  # again. An environment variable is a redirect for one invocation and does
  # not survive a restart, so the file is the store, never the environment.
  #
  # Prefer a channel ROOT, derived from the source we ACTUALLY fetched from by
  # stripping its trailing /<version>: <root>/<version> composes, so one record
  # keeps serving after an upgrade. Deriving it rather than trusting an ambient
  # PYXIS_CHANNEL keeps the record honest about where the bytes came from; the
  # explicit value is used only when no root can be derived.
  #
  # A source with no root — an air-gapped copy, a one-release mirror — is
  # recorded flat instead. It names this release's directory only, and the
  # version recorded above it is what says which.
  CHANNEL=""
  FLAT=""
  if [ -n "${PYXIS_ARTIFACT_SOURCE:-}" ]; then
    src="${PYXIS_ARTIFACT_SOURCE%/}"
    case "$src" in
      */"$VERSION") CHANNEL="${src%/$VERSION}" ;;
      *) FLAT="$src" ;;
    esac
  fi
  if [ -z "$CHANNEL" ] && [ -n "${PYXIS_CHANNEL:-}" ]; then
    CHANNEL="${PYXIS_CHANNEL%/}"
    FLAT=""
  fi
  {
    echo "PYXIS_SYSTEM_VERSION=$VERSION"
    echo "PYXIS_MANIFEST_SHA256=$MANIFEST_SHA256"
    [ -z "$CHANNEL" ] || echo "PYXIS_CHANNEL=$CHANNEL"
    [ -z "$FLAT" ] || echo "PYXIS_ARTIFACT_SOURCE=$FLAT"
    if [ -z "${PYXIS_ARTIFACT_SOURCE:-}" ] && { [ "$RELEASE_PROVIDER" = "forgejo" ] || [ -n "$RELEASE_TOKEN_ENV" ] || [ -n "${PYXIS_RELEASE_REPOSITORY:-}" ]; }; then
      echo "PYXIS_RELEASE_PROVIDER=$RELEASE_PROVIDER"
      echo "PYXIS_RELEASE_BASE_URL=$RELEASE_BASE_URL"
      echo "PYXIS_RELEASE_REPOSITORY=$REPO"
      echo "PYXIS_RELEASE_TOKEN_ENV=$RELEASE_TOKEN_ENV"
    fi
  } > "$CONFIG_DIR/release.env"
  if [ -n "$CHANNEL" ]; then
    echo "pyxis-install: recorded the release pin and the channel $CHANNEL in $CONFIG_DIR/release.env (so \`pyxis init\` needs no flags)"
  elif [ -n "$FLAT" ]; then
    echo "pyxis-install: recorded the release pin and the source $FLAT in $CONFIG_DIR/release.env (so \`pyxis init\` needs no flags for $VERSION)"
  else
    echo "pyxis-install: recorded the release pin in $CONFIG_DIR/release.env (so \`pyxis init\` needs no pin flags)"
  fi
fi

# ---- machine shell setup, owned by the verified Go binary ----
# Old explicitly selected releases and pins predating this verb remain
# installable. New releases carry the launcher assets inside the binary;
# no source checkout or extra download is needed.
if "$INSTALL_DIR/pyxis" shell install --help >/dev/null 2>&1; then
  if ! "$INSTALL_DIR/pyxis" shell install; then
    echo "pyxis-install: the CLI is installed, but zsh setup failed. Retry:" >&2
    echo "  \"$INSTALL_DIR/pyxis\" shell install" >&2
    exit 1
  fi
fi

# ---- PATH note + next steps (init is the user's to run) ----
case ":$PATH:" in
  *":$INSTALL_DIR:"*) ;;
  *) echo "pyxis-install: add it to your PATH for this shell and your profile:" >&2
     echo "  export PATH=\"$INSTALL_DIR:\$PATH\"" >&2 ;;
esac
echo "pyxis-install: done. Next, inside a repo you want to set up:  pyxis init  (or: pyxis --help)"
